#!/usr/bin/env python3
"""Guided setup wizard for the Sukanda Onelink MCP server.

Runs entirely on the Python standard library. It never prints a password and
never writes credentials anywhere except the local, gitignored .env file.

    python3 setup.py                  interactive guided setup
    python3 setup.py --show-config    print/write the MCP client config snippet
    python3 setup.py --verify         secret scan + connectivity + MCP handshake
    python3 setup.py --no-verify      guided setup without live network checks
    python3 setup.py --help           this message
"""

from __future__ import annotations

import getpass
import json
import os
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ENV_PATH = HERE / ".env"
LOCAL_CONFIG = HERE / "mcp-config.local.json"
SERVER_PATH = HERE / "server.py"

# Built in pieces so no real credential assignment ever appears in source code.
KEY_PASSWORD = "SUKANDA_" + "PASSWORD"
KEY_EMAIL = "SUKANDA_" + "EMAIL"
KEY_WAREHOUSE = "SUKANDA_" + "WAREHOUSE"
KEY_SUBSCRIBER = "SUKANDA_" + "SUBSCRIBER"

CLIENT_CONFIG_PATHS = [
    ("WorkBuddy", "~/.workbuddy-ai/mcp.json"),
    ("Claude Desktop (macOS)", "~/Library/Application Support/Claude/claude_desktop_config.json"),
    ("Claude Desktop (Windows)", "%APPDATA%\\Claude\\claude_desktop_config.json"),
    ("Cursor (per project)", ".cursor/mcp.json"),
]

HELP = __doc__


def step(n: str, text: str) -> None:
    print(f"\n[{n}] {text}")


def info(text: str) -> None:
    print(f"      {text}")


def ask(prompt: str, default: str = "") -> str:
    try:
        answer = input(f"      {prompt} ").strip()
    except (EOFError, KeyboardInterrupt):
        print()
        return default
    return answer or default


def ask_secret(prompt: str) -> str:
    # getpass tries to open /dev/tty, which can block forever when stdin is a
    # pipe (CI, scripted setup, ssh without a tty). Only use it on a real TTY.
    if not sys.stdin.isatty():
        info("(non-interactive stdin: reading the password as a normal line)")
        return ask(prompt)
    try:
        return getpass.getpass(f"      {prompt} ")
    except (EOFError, KeyboardInterrupt):
        print()
        return ""


def run(args: list[str], label: str) -> int:
    """Run a local script, streaming its output. Returns the exit code."""
    info(f"$ {label}")
    try:
        proc = subprocess.run(
            [sys.executable, *args], cwd=HERE, text=True,
            stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
        )
    except OSError as exc:
        info(f"could not start: {exc}")
        return 1
    for line in proc.stdout.splitlines():
        info(line)
    return proc.returncode


def check_python() -> bool:
    ok = sys.version_info >= (3, 9)
    step("1/6", "Checking Python version")
    if ok:
        info(f"Python {sys.version.split()[0]} - OK (3.9+ required)")
    else:
        info(f"Python {sys.version.split()[0]} is too old. Please install Python 3.9+.")
    return ok


def git_ignored(rel: str) -> bool | None:
    """True/False when inside a git repo, None when git cannot be used."""
    try:
        rc = subprocess.run(
            ["git", "check-ignore", "-q", rel], cwd=HERE,
            stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
        ).returncode
    except OSError:
        return None
    if rc == 0:
        return True
    if rc == 1:
        return False
    return None  # e.g. "fatal: not a git repository"


def check_ignore_rules() -> None:
    step("2/6", "Checking that secrets are gitignored")
    state = git_ignored(".env")
    if state is True:
        info(".env is ignored by git - credentials cannot be committed accidentally")
    elif state is False:
        info("WARNING: .env is NOT ignored. Add '.env' to .gitignore before committing.")
    else:
        info("git not available here - skipping the ignore check")
    local = git_ignored(LOCAL_CONFIG.name)
    if local is False:
        info("WARNING: mcp-config.local.json is not ignored; do not commit it.")


def read_existing_env() -> dict[str, str]:
    if not ENV_PATH.is_file():
        return {}
    values: dict[str, str] = {}
    for line in ENV_PATH.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if line and not line.startswith("#") and "=" in line:
            key, _, value = line.partition("=")
            values[key.strip()] = value.strip().strip('"').strip("'")
    return values


def write_env(email: str, password: str, warehouse: str = "") -> None:
    """Atomically write .env with 0600 permissions. Never prints the password."""
    lines = [
        "# Generated by setup.py. Local only - NEVER commit this file.",
        f"{KEY_EMAIL}={email}",
        f"{KEY_PASSWORD}={password}",
        f"{KEY_SUBSCRIBER}=web_buyer",
        f"{KEY_WAREHOUSE}={warehouse}",
        "",
        "# Optional: SUKANDA_TOKEN + SUKANDA_REFRESH_TOKEN can replace the password.",
        "# Optional: SUKANDA_API_BASE overrides the production API base.",
        "",
    ]
    tmp = ENV_PATH.with_suffix(".env.tmp")
    fd = os.open(tmp, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as fh:
            fh.write("\n".join(lines))
    except Exception:
        tmp.unlink(missing_ok=True)
        raise
    os.replace(tmp, ENV_PATH)
    os.chmod(ENV_PATH, 0o600)


def collect_credentials() -> None:
    step("3/6", "Buyer credentials")
    existing = read_existing_env()
    if existing.get(KEY_PASSWORD) or existing.get(KEY_EMAIL):
        info("An existing .env was found (credentials are hidden).")
        keep = ask("Keep the existing credentials? [Y/n]", "y").lower()
        if keep.startswith("y"):
            info("Keeping existing .env unchanged.")
            return
    info("Enter the same login you use on the buyer portal.")
    email = ask("Buyer email:", existing.get(KEY_EMAIL, ""))
    password = ask_secret("Buyer password (input hidden):")
    if not email or not password:
        info("Email and password are both required - nothing was written.")
        raise SystemExit(2)
    warehouse = ask("Ship-to / warehouse UUID (press Enter to auto-resolve):", "")
    write_env(email, password, warehouse)
    info(f"Wrote .env with mode 0600 (password not shown, length {len(password)} chars).")


def build_config() -> dict:
    return {
        "mcpServers": {
            "sukanda-onelink": {
                "command": sys.executable,
                "args": [str(SERVER_PATH)],
                "env": {},
            }
        }
    }


def show_config(write_file: bool = True) -> None:
    step("4/6", "MCP client configuration")
    config = build_config()
    LOCAL_CONFIG.write_text(json.dumps(config, indent=2) + "\n", encoding="utf-8")
    ignored = git_ignored(LOCAL_CONFIG.name)
    if ignored is True:
        info(f"Saved a copy to {LOCAL_CONFIG.name} (gitignored, contains your real paths).")
    elif ignored is False:
        info(f"Saved a copy to {LOCAL_CONFIG.name} - WARNING: not gitignored, do NOT commit it.")
    else:
        info(f"Saved a copy to {LOCAL_CONFIG.name} - keep this file private (contains real paths).")
    print()
    print(json.dumps(config, indent=2))
    print()
    info("Merge the 'sukanda-onelink' entry into the mcpServers object of:")
    for name, path in CLIENT_CONFIG_PATHS:
        info(f"  {name:<28} {path}")
    info("Do NOT overwrite other servers already in that file.")
    info("Then restart the client and Trust the new server (WorkBuddy).")


def verify(skip_live: bool = False) -> bool:
    step("5/6", "Verification")
    ok = True
    if run(["check_secrets.py"], "python3 check_secrets.py") != 0:
        ok = False
    if skip_live:
        info("Skipping live checks (--no-verify).")
        return ok
    if run(["server.py", "--check"], "python3 server.py --check") != 0:
        ok = False
    if run(["test_client.py"], "python3 test_client.py") != 0:
        ok = False
    return ok


def next_steps(ok: bool) -> None:
    step("6/6", "Done" if ok else "Setup finished with warnings")
    if not ok:
        info("One or more checks failed. See the output above before continuing.")
    info("1. Paste the config snippet into your MCP client and restart it.")
    info("2. Ask: 'What's new in the Sukanda catalog this month?'")
    info("3. Before any future commit, run: python3 check_secrets.py")
    info("Full guide: README.md")


def wizard(skip_live: bool) -> int:
    print("=" * 68)
    print(" Sukanda Onelink MCP - guided setup")
    print("=" * 68)
    print(" This wizard will: check Python, verify .env is gitignored, ask for")
    print(" your buyer login (hidden input), write .env with private permissions,")
    print(" generate your MCP client config, and run the verification suite.")
    print(" Your password is never printed and never leaves this machine.")
    if not check_python():
        return 1
    check_ignore_rules()
    collect_credentials()
    show_config()
    ok = verify(skip_live)
    next_steps(ok)
    return 0 if ok else 1


def main(argv: list[str]) -> int:
    if "--help" in argv or "-h" in argv:
        print(HELP)
        return 0
    if "--show-config" in argv:
        show_config()
        return 0
    if "--verify" in argv:
        return 0 if verify() else 1
    return wizard(skip_live="--no-verify" in argv)


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
